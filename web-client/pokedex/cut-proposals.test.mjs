import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { JSDOM } from 'jsdom';
const root = process.env.POKEDEX_WEB_RELEASE || 'target/minnesota-pokedex-web/pokedex/current';
const curation = JSON.parse(fs.readFileSync('planning/minnesota/pokemon/roster-curation.json', 'utf8'));
const expectedCount = curation.active_species_count;
const expectedFamilies = curation.active_family_count;
const expectedCutCount = curation.source_species_count - expectedCount;
const script = fs.readFileSync('web-client/pokedex/app.js', 'utf8');
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'pokedex.json'), 'utf8'));
function page(file, query = '') {
 const dom = new JSDOM(fs.readFileSync(path.join(root, file), 'utf8'), { url: `https://example.test/pokedex/${file}${query}`, runScripts: 'outside-only' });
 dom.window.matchMedia = () => ({ matches: false, addEventListener() {} });
 dom.window.eval(script);
 return dom;
}
assert.equal(catalog.species.length, expectedCount);
assert.equal(catalog.cut_species_count, expectedCutCount);
assert.equal(catalog.cut_species.length, expectedCutCount);
assert.equal(catalog.cut_family_count, curation.retired_families.length);
assert.ok(catalog.species.every(species => species.status === 'active'));
assert.ok(catalog.cut_species.every(species => species.status === 'cut' && species.cut_reason));
const cutDom = page('index.html');
const cutDoc = cutDom.window.document;
const cutToggle = cutDoc.querySelector('#cut-filter');
const cutVisible = () => [...cutDoc.querySelectorAll('.pokemon-card:not([hidden])')];
assert.equal(cutToggle.checked, false);
cutToggle.click();
assert.equal(cutToggle.checked, true);
assert.equal(cutVisible().length, curation.source_species_count);
assert.ok(cutVisible().slice(0, expectedCount).every(card => card.dataset.cut === 'false'));
assert.ok(cutVisible().slice(expectedCount).every(card => card.dataset.cut === 'true'));
assert.match(cutDoc.querySelector('#result-count').textContent, new RegExp(`${expectedCutCount} cut proposals`));
assert.equal(new URL(cutDom.window.location.href).searchParams.get('cut'), '1');
cutDoc.querySelector('[data-view="families"]').click();
assert.equal(cutDoc.querySelectorAll('.family-card:not([hidden])').length, expectedFamilies + curation.retired_families.length);
cutDoc.querySelector('[data-view="species"]').click();
cutDoc.querySelector('[data-type="WATER"]').click();
assert.ok(cutVisible().every(card => card.dataset.types.split(' ').includes('WATER')));
assert.ok(cutVisible().some(card => card.dataset.cut === 'true'));
cutDoc.querySelector('#clear-filters').click();
assert.equal(cutToggle.checked, false);
assert.equal(cutVisible().length, expectedCount);
assert.equal(new URL(cutDom.window.location.href).searchParams.has('cut'), false);
const firstCut = catalog.cut_species[0];
const cutSearch = page('index.html', `?cut=1&q=${encodeURIComponent(firstCut.identity.name)}`);
assert.deepEqual([...cutSearch.window.document.querySelectorAll('.pokemon-card:not([hidden])')].map(card => card.dataset.id), [firstCut.identity.id]);
cutSearch.window.document.querySelector('#cut-filter').click();
assert.equal(cutSearch.window.document.querySelectorAll('.pokemon-card:not([hidden])').length, 0);
cutSearch.window.document.querySelector('#cut-filter').click();
cutSearch.window.document.querySelector(`[data-save="${firstCut.identity.id}"]`).click();
cutSearch.window.document.querySelector('#notebook-filter').click();
assert.equal(cutSearch.window.document.querySelectorAll('.pokemon-card:not([hidden])').length, 1);
assert.equal(cutSearch.window.document.querySelector('[data-saved-count]').textContent, '1');
cutSearch.window.document.querySelector('#cut-filter').click();
assert.equal(cutSearch.window.document.querySelectorAll('.pokemon-card:not([hidden])').length, 0);
assert.equal(cutSearch.window.document.querySelector('[data-saved-count]').textContent, '0');
cutSearch.window.history.pushState(null, '', '?cut=1');
cutSearch.window.dispatchEvent(new cutSearch.window.PopStateEvent('popstate'));
assert.equal(cutSearch.window.document.querySelector('#cut-filter').checked, true);
assert.equal(cutSearch.window.document.querySelectorAll('.pokemon-card:not([hidden])').length, curation.source_species_count);
const cutEntry = page(`species/${firstCut.identity.name.toLowerCase()}.html`).window.document;
assert.match(cutEntry.querySelector('.cut-notice').textContent, /removed from the active regional Pokédex/);
assert.ok(cutEntry.querySelector('.cut-notice').textContent.includes(firstCut.cut_reason));
assert.equal(cutEntry.querySelector('.breadcrumb a').getAttribute('href'), '/pokedex/?cut=1#guide');
assert.equal(cutEntry.querySelector('.breadcrumb span').textContent, 'CUT PROPOSAL');
assert.equal(cutEntry.querySelector('.entry-pager a strong')?.textContent, catalog.cut_species[1].identity.name);
console.log(`PASS: ${expectedCutCount} cut proposals are hidden by default; toggle, shared URLs/history, search/type filters, families, favorites, reset and labeled detail pages preserve the active roster`);
