import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { JSDOM } from 'jsdom';

const release = process.env.POKEDEX_WEB_RELEASE;
const baseline = process.env.POKEDEX_WEB_BASELINE;
assert.ok(release && baseline, 'Set POKEDEX_WEB_RELEASE and POKEDEX_WEB_BASELINE');
const read = file => fs.readFileSync(path.join(release, file), 'utf8');
const before = file => fs.readFileSync(path.join(baseline, file), 'utf8');
assert.deepEqual(JSON.parse(read('pokedex.json')), JSON.parse(before('pokedex.json')), 'all species, move and cry metadata stays exact');
for (const file of ['index.html', 'moves.html', ...fs.readdirSync(path.join(release, 'species')).map(name => `species/${name}`)]) {
  const html = read(file);
  assert.equal((html.match(/href="\/pokedex\/state-fair.html"/g) || []).length, 1, `${file}: one accessible fair tab`);
  const normalized = html.replace(/\/pokedex\/releases\/20261027-state-fair-realtime-22/g, '/pokedex/releases/20261027-state-fair-21');
  assert.equal(normalized, before(file), `${file}: only the navigation and immutable URLs change`);
}
assert.equal(read('app.js'), before('app.js'), 'existing species, cry and battle controls remain exact');
const dom = new JSDOM(read('state-fair.html'), { url: 'https://example.test/pokedex/state-fair.html', runScripts: 'outside-only' });
const { window } = dom;
const doc = window.document;
const video = doc.querySelector('video');
const play = doc.querySelector('[data-showcase-play]');
const status = doc.querySelector('[role=status]');
assert.equal(video.preload, 'none');
assert.equal(video.hasAttribute('autoplay'), false);
assert.equal(video.hasAttribute('src'), false, 'no video request before a gesture');
assert.equal(video.controls, true);
assert.equal(video.playsInline, true);
assert.equal(doc.querySelector('.main-nav [aria-current=page]').textContent, 'State Fair');
assert.equal(doc.querySelectorAll('[data-showcase-time]').length, 6);
let ready = 0;
let plays = 0;
let pauses = 0;
let failure = false;
let scrolls = 0;
video.scrollIntoView = () => { scrolls++; };
Object.defineProperty(video, 'readyState', { get: () => ready });
Object.defineProperty(video, 'duration', { get: () => 58 });
Object.defineProperty(video, 'ended', { get: () => false });
video.play = () => { plays++; return failure ? Promise.reject(new Error('network')) : Promise.resolve(); };
video.pause = () => { pauses++; video.dispatchEvent(new window.Event('pause')); };
window.eval(read('state-fair.js'));
assert.equal(plays, 0, 'script never autoplays');
doc.querySelector('[data-showcase-start]').click();
assert.equal(scrolls, 1, 'the prominent play control brings the fitted player into view');
await new Promise(setImmediate);
assert.equal(plays, 1);
assert.match(video.src, /\/pokedex\/media\/showcases\/20261027-state-fair-v2\/state-fair-chaos.mp4$/);
ready = 1;
video.dispatchEvent(new window.Event('loadedmetadata'));
assert.equal(video.currentTime, 0);
video.dispatchEvent(new window.Event('playing'));
assert.equal(play.hidden, true);
assert.match(status.textContent, /Playing State Fair Chaos/);
doc.querySelector('[data-showcase-time="24"]').click();
await new Promise(setImmediate);
assert.equal(video.currentTime, 24, 'chapter seeks to the real movie timestamp');
video.dispatchEvent(new window.Event('ended'));
assert.equal(play.hidden, false);
assert.match(play.textContent, /Replay/);
play.click();
await new Promise(setImmediate);
assert.equal(video.currentTime, 0, 'replay returns to the beginning');
failure = true;
play.click();
await new Promise(setImmediate);
assert.equal(play.hidden, false);
assert.match(status.textContent, /could not start/);
video.dispatchEvent(new window.Event('error'));
assert.match(status.textContent, /could not load/);
window.dispatchEvent(new window.Event('pagehide'));
assert.equal(pauses, 1, 'leaving the page stops the movie');
assert.ok(doc.querySelector('a[href$="/whole-map.png"] img'), 'complete map remains available independently of playback');
dom.window.close();
console.log('PASS: every page gains the fair tab; all prior data and controls stay exact; no autoplay, playback, chapters, replay, failure and page-exit behavior work.');
